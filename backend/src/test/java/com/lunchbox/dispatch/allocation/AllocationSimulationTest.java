import com.lunchbox.common.geo.Geo;
import com.lunchbox.dispatch.allocation.AllocationModel.Assignment;
import com.lunchbox.dispatch.allocation.AllocationModel.Job;
import com.lunchbox.dispatch.allocation.AllocationModel.Presence;
import com.lunchbox.dispatch.allocation.AllocationModel.Result;
import com.lunchbox.dispatch.allocation.AllocationModel.Rider;
import org.junit.jupiter.api.Test;
import org.locationtech.jts.geom.Point;

import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Instant;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.HashMap;
import java.util.HashSet;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Random;
import java.util.Set;
import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Simulated Hyderabad days: the allocation engine against the greedy nearest-rider rule it replaced, on the same
 * seeded scenarios. Writes {@code build/reports/allocation-simulation.md}; with {@code -DupdateReports=true} also
 * {@code docs/reports/allocation-simulation.md}.
 */
class AllocationSimulationTest {

    private static final Instant SHIFT_START = Instant.parse("2026-10-20T03:30:00Z");
    private static final Instant SHIFT_END = Instant.parse("2026-10-20T08:30:00Z");
    private static final AllocationWeights W = AllocationWeights.DEFAULTS;
    private static final TravelTimeProvider TRAVEL = new EstimatedTravelTimes();

    record Scenario(String name, List<Job> jobs, List<Rider> riders, Map<UUID, Point> schools) {
    }

    record Metrics(int assigned, int unassigned, double km, int schoolVisits, double maxLoadShare, double loadStdDev,
                   int ridersUsed, long millis, double cost) {
    }

    @Test
    void engineBeatsGreedyOnSimulatedDaysAndScales() throws Exception {
        List<Scenario> scenarios = List.of(
                scenario("Small: 120 boxes, 15 riders, 8 schools", 1, 120, 15, 8, 12),
                scenario("Typical: 600 boxes, 60 riders, 30 schools", 2, 600, 60, 30, 12),
                scenario("Tight: 600 boxes, 50 riders (capacity short)", 3, 600, 50, 30, 11),
                scenario("Large: 3000 boxes, 250 riders, 120 schools", 4, 3000, 250, 120, 14));

        StringBuilder md = new StringBuilder("""
                # Rider allocation: simulation report

                Generated by `AllocationSimulationTest` (seeded, repeatable). Each scenario is a Hyderabad school day:
                schools spread over the city, homes within ~4 km of their school, riders starting from random homes with
                an 8 km service radius and capacity 8–16. Distances are estimated road km (straight line × 1.35) from the
                rider's start to each home. **Greedy** is the rule used before ADR-0023 (orders in pickup order, nearest
                rider, distance halved for a school the rider already serves). **Engine** is the min-cost assignment with
                batching, workload, rating and reliability terms and default weights.

                | Scenario | Method | Assigned | Unassigned | Road km to homes | School visits | Busiest rider's share | Load std dev | Riders used | Total cost | Time |
                |---|---|---|---|---|---|---|---|---|---|---|
                """);
        for (Scenario s : scenarios) {
            Metrics greedy = greedy(s);
            long t0 = System.nanoTime();
            Result result = AllocationEngine.allocate(s.jobs(), s.riders(), W, TRAVEL, null);
            Metrics engine = metrics(s, toMap(result), (System.nanoTime() - t0) / 1_000_000);

            row(md, s.name(), "Greedy", greedy);
            row(md, s.name(), "Engine", engine);

            assertThat(engine.assigned()).as(s.name() + ": serves at least as many").isGreaterThanOrEqualTo(greedy.assigned());
            assertThat(engine.cost()).as(s.name() + ": lower total cost under the same weights")
                    .isLessThanOrEqualTo(greedy.cost() + 1e-6);
            assertThat(engine.loadStdDev()).as(s.name() + ": spreads work at least as evenly")
                    .isLessThanOrEqualTo(greedy.loadStdDev() + 1e-9);
            assertThat(engine.millis()).as(s.name() + ": solves fast enough for a 10-minute job").isLessThan(30_000);
        }
        md.append("""

                **Reading the table.** *Total cost* is the engine's objective (km-equivalents: riding distance, a charge
                per school a rider visits, a workload term that grows with the square of each rider's load, rating and
                reliability), applied to both methods' assignments with the same default weights; the test fails if the
                engine is ever worse on it, serves fewer boxes, or spreads work less evenly. Fewer school visits mean fewer
                separate trips to school gates; a lower busiest-rider share and standard deviation mean fairer work. The
                individual columns trade against each other: greedy fills its nearest riders to capacity, which can mean
                fewer school visits but overloaded riders; the engine shares the work unless a whole school can go to one
                rider. Ops tune the balance in Settings → Rider allocation (`allocation.weights`).
                """);
        Path out = Path.of("build", "reports", "allocation-simulation.md");
        Files.createDirectories(out.getParent());
        Files.writeString(out, md.toString());
        if (Boolean.getBoolean("updateReports")) {
            Path committed = Path.of("..", "docs", "reports", "allocation-simulation.md");
            Files.createDirectories(committed.getParent());
            Files.writeString(committed, md.toString());
        }
    }

    private static void row(StringBuilder md, String scenario, String method, Metrics m) {
        md.append(String.format(Locale.ROOT, "| %s | %s | %d | %d | %.1f | %d | %.0f%% | %.2f | %d | %.0f | %d ms |%n", scenario,
                method, m.assigned(), m.unassigned(), m.km(), m.schoolVisits(), m.maxLoadShare() * 100, m.loadStdDev(),
                m.ridersUsed(), m.cost(), m.millis()));
    }

    private static Scenario scenario(String name, long seed, int boxes, int riderCount, int schoolCount, int maxCapacity) {
        Random rnd = new Random(seed);
        Map<UUID, Point> schools = new HashMap<>();
        List<UUID> schoolIds = new ArrayList<>();
        for (int i = 0; i < schoolCount; i++) {
            UUID id = new UUID(seed, i);
            schools.put(id, Geo.point(17.30 + rnd.nextDouble() * 0.20, 78.36 + rnd.nextDouble() * 0.24));
            schoolIds.add(id);
        }
        List<Job> jobs = new ArrayList<>();
        for (int i = 0; i < boxes; i++) {
            UUID school = schoolIds.get(rnd.nextInt(schoolIds.size()));
            Point s = schools.get(school);
            Point home = Geo.point(s.getY() + (rnd.nextDouble() - 0.5) * 0.07, s.getX() + (rnd.nextDouble() - 0.5) * 0.07);
            Instant start = Instant.parse("2026-10-20T04:30:00Z").plusSeconds(1800L * (school.getLeastSignificantBits() % 3));
            jobs.add(new Job(new UUID(seed + 1000, i), school, home, start, start.plusSeconds(2700), start.plusSeconds(7200), false));
        }
        List<Rider> riders = new ArrayList<>();
        for (int i = 0; i < riderCount; i++) {
            Point start = Geo.point(17.30 + rnd.nextDouble() * 0.20, 78.36 + rnd.nextDouble() * 0.24);
            int capacity = 8 + rnd.nextInt(Math.max(1, maxCapacity - 7));
            riders.add(new Rider(new UUID(seed + 2000, i), "R" + i, start, capacity, 0, Set.of(), 8000, null, SHIFT_START,
                    SHIFT_END, Presence.NOT_STARTED, 3.5 + rnd.nextDouble() * 1.5, 0.75 + rnd.nextDouble() * 0.25, Set.of()));
        }
        return new Scenario(name, jobs, riders, schools);
    }

    /** The pre-ADR-0023 rule, reproduced for comparison. */
    private static Metrics greedy(Scenario s) {
        long t0 = System.nanoTime();
        Map<UUID, Integer> load = new HashMap<>();
        Map<UUID, Set<UUID>> served = new HashMap<>();
        Map<UUID, UUID> out = new HashMap<>();
        List<Job> ordered = s.jobs().stream().sorted(Comparator.comparing(Job::pickupWindowStart)).toList();
        for (Job job : ordered) {
            Rider best = null;
            double bestScore = Double.MAX_VALUE;
            for (Rider r : s.riders()) {
                double d = Geo.haversineMeters(r.start(), job.pickup());
                if (load.getOrDefault(r.partnerId(), 0) >= r.capacity() || d > r.serviceRadiusM()) {
                    continue;
                }
                double score = served.getOrDefault(r.partnerId(), Set.of()).contains(job.schoolId()) ? d * 0.5 : d;
                if (score < bestScore) {
                    bestScore = score;
                    best = r;
                }
            }
            if (best != null) {
                out.put(job.orderId(), best.partnerId());
                load.merge(best.partnerId(), 1, Integer::sum);
                served.computeIfAbsent(best.partnerId(), k -> new HashSet<>()).add(job.schoolId());
            }
        }
        return metrics(s, out, (System.nanoTime() - t0) / 1_000_000);
    }

    private static Map<UUID, UUID> toMap(Result r) {
        Map<UUID, UUID> m = new HashMap<>();
        for (Assignment a : r.assignments()) {
            m.put(a.orderId(), a.partnerId());
        }
        return m;
    }

    private static Metrics metrics(Scenario s, Map<UUID, UUID> assignment, long millis) {
        Map<UUID, Rider> riders = new HashMap<>();
        s.riders().forEach(r -> riders.put(r.partnerId(), r));
        double km = 0;
        Map<UUID, Integer> load = new HashMap<>();
        Set<String> visits = new HashSet<>();
        for (Job j : s.jobs()) {
            UUID p = assignment.get(j.orderId());
            if (p == null) {
                continue;
            }
            km += Geo.haversineMeters(riders.get(p).start(), j.pickup()) * W.roadDetourFactor() / 1000;
            load.merge(p, 1, Integer::sum);
            visits.add(p + ":" + j.schoolId());
        }
        int assigned = assignment.size();
        double mean = s.riders().isEmpty() ? 0 : (double) assigned / s.riders().size();
        double var = 0;
        for (Rider r : s.riders()) {
            double l = load.getOrDefault(r.partnerId(), 0);
            var += (l - mean) * (l - mean);
        }
        double std = s.riders().isEmpty() ? 0 : Math.sqrt(var / s.riders().size());
        int max = load.values().stream().mapToInt(Integer::intValue).max().orElse(0);
        // The engine's objective, applied to this assignment (same weights for both methods).
        double cost = 0;
        for (Job j : s.jobs()) {
            UUID p = assignment.get(j.orderId());
            if (p == null) {
                cost += W.unassignedPenaltyKm();
                continue;
            }
            Rider r = riders.get(p);
            cost += W.distancePerKm() * Geo.haversineMeters(r.start(), j.pickup()) * W.roadDetourFactor() / 1000
                    + W.ratingKm() * (1 - (r.rating() == null ? 4.0 : r.rating()) / 5)
                    + W.reliabilityKm() * (1 - r.reliability());
        }
        for (Rider r : s.riders()) {
            int l = load.getOrDefault(r.partnerId(), 0);
            cost += W.workloadKm() * l * l / (double) r.capacity();
        }
        cost += W.newSchoolKm() * visits.size();
        return new Metrics(assigned, s.jobs().size() - assigned, km, visits.size(), assigned == 0 ? 0 : (double) max / assigned,
                std, load.size(), millis, cost);
    }
}
