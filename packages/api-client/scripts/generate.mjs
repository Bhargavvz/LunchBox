#!/usr/bin/env node
/**
 * Regenerates src/generated/schema.ts from the backend's OpenAPI document.
 *
 * Source resolution (first match wins):
 *   1. OPENAPI_SOURCE env var (URL or file path)
 *   2. backend/build/openapi/openapi.json  (produced by `./gradlew generateOpenApiDocs`)
 *   3. http://localhost:8080/v3/api-docs  (a locally running backend)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const here = path.dirname(fileURLToPath(import.meta.url));
const pkgRoot = path.resolve(here, '..');
const repoRoot = path.resolve(pkgRoot, '..', '..');
const built = path.join(repoRoot, 'backend', 'build', 'openapi', 'openapi.json');

const source =
  process.env.OPENAPI_SOURCE ?? (fs.existsSync(built) ? built : 'http://localhost:8080/v3/api-docs');

const input = /^https?:\/\//.test(source) ? new URL(source) : new URL(`file://${path.resolve(source)}`);
console.log(`Generating API types from ${input.href}`);

const ast = await openapiTS(input, {
  alphabetize: true,
  exportType: true,
  defaultNonNullable: false,
});

const header = `/* eslint-disable */\n// AUTO-GENERATED by packages/api-client/scripts/generate.mjs — do not edit.\n// Source: ${source}\n\n`;
const outDir = path.join(pkgRoot, 'src', 'generated');
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'schema.ts'), header + astToString(ast));
console.log('Wrote src/generated/schema.ts');
